/** Normaliza o nome vindo do catálogo: minúsculas, sem acento, sem espaço/ponto/hífen. */
export function normalizeTechName(name: string): string {
  return name
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9+#]/g, "");
}

